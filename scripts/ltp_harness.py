"""
Build, boot and score the LTP syscalls subset for the SMP entry gate.

The gate (scripts/smp_entry_gate.py, criterion 4) reads
scripts/smp_entry_gate/ltp_results.tsv. This script produces it:

  build    Clone LTP (pinned tag) outside the repo, build it static with
           musl for one ISA, and build tests/ltp/runner.c, the PID 1 that
           runs the list.
  run      Pack the runner and the listed tests into MINIX root disks (one
           per chunk that fits), boot each under scripts/smoke_autokill.py
           and keep the serial logs.
  results  Turn serial logs into ltp_results.tsv rows. Rows whose result
           did not change keep their triage column. Pass every chunk log of
           an arch in one call: that arch's rows are replaced as a whole.

The disk is attached as the x86_64 IDE root (hda) and as the arm64 virtio-blk
device (vda); the kernel must mount it as the MINIX root on both.

The build tree lives outside the repository (default ../ltp-build next to
the main checkout). The kernel images are not built here.

Usage:
    python3 scripts/ltp_harness.py build --arch x86_64
    python3 scripts/ltp_harness.py run --arch x86_64 --log-dir DIR
    python3 scripts/ltp_harness.py results DIR/*.log
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ktm_host_safety as safety  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LTP_URL = "https://github.com/linux-test-project/ltp.git"
LTP_TAG = "20260930"
DEFAULT_LIST = ROOT / "tests" / "ltp" / "syscalls-ltp1.txt"
RUNNER_SRC = ROOT / "tests" / "ltp" / "runner.c"
RESULTS = ROOT / "scripts" / "smp_entry_gate" / "ltp_results.tsv"
SYSCALLS = Path("testcases") / "kernel" / "syscalls"

# Gate arch names; LTP and toolchains use the GNU tuple.
ARCHES = {"x86_64": "x86_64", "arm64": "aarch64"}
CONFIGURE_ARGS = ("--without-numa", "--without-tirpc", "--without-modules",
                  "--without-expect", "--without-perl", "--without-python",
                  "--without-bash")
# Static, non-PIE ET_EXEC like the ISD packages and the selftests.
CFLAGS = "-Os -fno-pie -ffunction-sections -fdata-sections"
LDFLAGS = "-static -no-pie -s -Wl,--gc-sections"
ARM64_LDFLAGS = " -Wl,-z,max-page-size=4096"
# Linux UAPI directories the x86_64 musl wrapper does not search.
X86_UAPI_DIRS = ("linux", "asm-generic", "mtd", "rdma", "misc", "drm",
                 "sound", "video")

# inject_init_minix.py --format-large: MINIX v1, 65535 1 KiB zones,
# 2048 inodes, 14-character names.
DISK_BYTES = 65535 * 1024
DISK_PAYLOAD_BUDGET = 56 * 1024 * 1024
DISK_FILE_BUDGET = 1800
MINIX_NAME_MAX = 14

BEGIN_RE = re.compile(r"LTP_BEGIN (\S+)")
RESULT_RE = re.compile(r"LTP_RESULT (\S+) (PASS|FAIL|BROK|TWARN|TCONF|HANG)\b")
DONE_RE = re.compile(r"LTP_RUN_DONE total=(\d+)")
PANIC_RE = re.compile(r"KERNEL PANIC|DOUBLE PANIC")
FATAL_RESULTS = ("PANIC", "HANG")
TSV_HEADER = (
    "# LTP syscalls subset on both ISAs (smp_entry_gate.py criterion 4).\n"
    "# Generated by scripts/ltp_harness.py results; edit only the triage\n"
    "# column: red:<path to the filed red case> or approved:<who, date, why>.\n"
    "# arch\ttest\tresult\ttriage\n"
)


def main_checkout() -> Path:
    """The checkout owning the git dir (holds the untracked toolchain/)."""
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--path-format=absolute",
             "--git-common-dir"],
            check=True, capture_output=True, text=True, timeout=10).stdout
        return Path(out.strip()).parent
    except (OSError, subprocess.SubprocessError):
        return ROOT


def default_build_dir() -> Path:
    return Path(os.environ.get("IR0_LTP_BUILD",
                               main_checkout().parent / "ltp-build"))


def toolchain(arch: str) -> dict[str, str]:
    """CC and binutils for @arch, matching tests/selftests/Makefile."""
    if arch == "x86_64":
        return {"CC": os.environ.get("LTP_CC_X86_64", "x86_64-linux-musl-gcc")}
    cc = os.environ.get("LTP_CC_ARM64")
    if not cc:
        base = main_checkout() / "toolchain"
        for sub in ("aarch64-linux-musl", "aarch64-linux-musl-cross"):
            cand = base / sub / "bin" / "aarch64-linux-musl-gcc"
            if cand.is_file():
                cc = str(cand)
                break
        else:
            cc = shutil.which("aarch64-linux-musl-gcc") or ""
    if not cc:
        raise SystemExit("ltp: no aarch64-linux-musl-gcc "
                         "(scripts/setup_musl_aarch64.sh or LTP_CC_ARM64)")
    prefix = cc[:-len("gcc")]
    return {"CC": cc, "AR": prefix + "ar", "RANLIB": prefix + "ranlib",
            "STRIP": prefix + "strip"}


def flags(arch: str, build: Path) -> tuple[str, str]:
    cflags, ldflags = CFLAGS, LDFLAGS
    if arch == "x86_64":
        cflags += f" -isystem {build / 'uapi-x86_64'}"
    else:
        ldflags += ARM64_LDFLAGS
    return cflags, ldflags


def sh(argv: list[str], log: Path | None = None, **kw) -> None:
    if log is None:
        subprocess.run(argv, check=True, **kw)
        return
    with log.open("w") as fp:
        rc = subprocess.run(argv, stdout=fp, stderr=subprocess.STDOUT,
                            check=False, **kw).returncode
    if rc != 0:
        raise SystemExit(f"ltp: {' '.join(argv[:3])}... failed rc={rc} "
                         f"(log {log})")


# --- test list --------------------------------------------------------------

def read_tags(path: Path) -> list[str]:
    tags = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            tags.append(line)
    return tags


def runtest_entries(src: Path) -> dict[str, list[str]]:
    """tag -> argv from runtest/syscalls; shell-only entries are dropped."""
    entries = {}
    for raw in (src / "runtest" / "syscalls").read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        tag, *argv = line.split()
        if argv and not any(c in line for c in ";|&<>$`'\"="):
            entries[tag] = argv
    return entries


def source_dirs(src: Path) -> dict[str, Path]:
    """Binary name -> its syscalls source directory (relative to @src)."""
    dirs = {}
    for c_file in (src / SYSCALLS).rglob("*.c"):
        if (c_file.parent / "Makefile").is_file():
            dirs.setdefault(c_file.stem, c_file.parent.relative_to(src))
    return dirs


def selected(src: Path, list_file: Path) -> list[tuple[str, list[str]]]:
    entries = runtest_entries(src)
    out = []
    for tag in read_tags(list_file):
        if tag not in entries:
            raise SystemExit(f"ltp: {list_file.name}: '{tag}' is not a plain "
                             "runtest/syscalls entry")
        out.append((tag, entries[tag]))
    return out


# --- build ------------------------------------------------------------------

def ensure_source(build: Path) -> Path:
    src = build / "src"
    if not (src / "configure.ac").is_file():
        build.mkdir(parents=True, exist_ok=True)
        sh(["git", "clone", "-q", "--depth", "1", "--branch", LTP_TAG,
            LTP_URL, str(src)], timeout=600)
    if not (src / "configure").is_file():
        sh(["make", "autotools"], log=build / "autotools.log", cwd=src,
           timeout=600)
    uapi = build / "uapi-x86_64"
    uapi.mkdir(exist_ok=True)
    for name in X86_UAPI_DIRS + ("asm",):
        target = Path("/usr/include") / (
            "x86_64-linux-gnu/asm" if name == "asm" else name)
        link = uapi / name
        if target.is_dir() and not link.exists():
            link.symlink_to(target)
    return src


def ltp_make(src: Path, out: Path, rel: Path, log: Path, jobs: int) -> bool:
    (out / rel).mkdir(parents=True, exist_ok=True)
    with log.open("w") as fp:
        return subprocess.run(
            ["make", "-s", f"-j{jobs}", "-C", str(out / rel),
             "-f", str(src / rel / "Makefile"),
             f"top_srcdir={src}", f"top_builddir={out}"],
            stdout=fp, stderr=subprocess.STDOUT, check=False,
            timeout=1800).returncode == 0


def cmd_build(args) -> int:
    arch = args.arch
    build = args.build_dir.resolve()
    src = ensure_source(build)
    out = build / f"build-{ARCHES[arch]}"
    tools = toolchain(arch)
    cflags, ldflags = flags(arch, build)
    if not (out / "config.status").is_file():
        out.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ, PKG_CONFIG_LIBDIR="/nonexistent")
        cfg = [str(src / "configure"), "--prefix=/ltp", *CONFIGURE_ARGS,
               f"CFLAGS={cflags}", f"LDFLAGS={ldflags}",
               *(f"{k}={v}" for k, v in tools.items())]
        if arch == "arm64":
            cfg.insert(1, "--host=aarch64-linux-musl")
        sh(cfg, log=out / "configure.log", cwd=out, env=env, timeout=600)
    if not ltp_make(src, out, Path("lib"), out / "lib.log", args.jobs):
        raise SystemExit(f"ltp: lib failed ({out / 'lib.log'})")

    dirs = source_dirs(src)
    wanted = sorted({dirs[argv[0]] for _, argv in selected(src, args.list)
                     if argv[0] in dirs})
    failed = [rel for rel in wanted
              if not ltp_make(src, out, rel, out / f"{rel.name}.log", args.jobs)]
    for rel in failed:
        print(f"ltp: build FAIL {arch} {rel} ({out / (rel.name + '.log')})")

    runner = out / "ltp-runner"
    sh([tools["CC"], *cflags.split(), *ldflags.split(), "-o", str(runner),
        str(RUNNER_SRC)], timeout=120)
    missing = [tag for tag, argv in selected(src, args.list)
               if not (out / dirs.get(argv[0], Path("?")) / argv[0]).is_file()]
    print(f"ltp: {arch} built {len(wanted) - len(failed)}/{len(wanted)} dirs, "
          f"{len(missing)} listed tests without a binary"
          + (f": {' '.join(missing)}" if missing else ""))
    return 1 if failed or missing else 0


# --- run --------------------------------------------------------------------

def helpers(test_dir: Path, binary: str) -> list[Path]:
    """Helper programs a test execs by name (execve01_child, ...)."""
    return sorted(p for p in test_dir.iterdir()
                  if p.is_file() and os.access(p, os.X_OK)
                  and p.name != binary and not p.suffix
                  and (p.name.startswith(binary + "_") or "_child" in p.name
                       or "_helper" in p.name))


def plan_chunks(src: Path, out: Path, list_file: Path):
    """Split the list into disks that fit the MINIX v1 budget."""
    dirs = source_dirs(src)
    chunks, cur, files, size = [], [], {}, 0
    for tag, argv in selected(src, list_file):
        test_dir = out / dirs.get(argv[0], Path("?"))
        binary = test_dir / argv[0]
        if not binary.is_file():
            print(f"ltp: skip {tag}: {binary} not built", file=sys.stderr)
            continue
        need = {p.name: p for p in [binary, *helpers(test_dir, argv[0])]
                if p.name not in files}
        add = sum(p.stat().st_size for p in need.values())
        if cur and (size + add > DISK_PAYLOAD_BUDGET or
                    len(files) + len(need) > DISK_FILE_BUDGET):
            chunks.append((cur, files))
            cur, files, size = [], {}, 0
            need = {p.name: p for p in [binary, *helpers(test_dir, argv[0])]}
            add = sum(p.stat().st_size for p in need.values())
        files.update(need)
        size += add
        cur.append((tag, argv))
    if cur:
        chunks.append((cur, files))
    return chunks


def disk_names(files: dict[str, Path]) -> dict[str, str]:
    """Binary name -> name on disk; MINIX v1 keeps 14 characters."""
    names = {}
    aliases = 0
    for name in sorted(files):
        if len(name) <= MINIX_NAME_MAX:
            names[name] = name
        else:
            names[name] = f"long{aliases:04d}"
            aliases += 1
    return names


def inject(disk: Path, src: Path, dest: str) -> None:
    sh([sys.executable, str(ROOT / "scripts" / "inject_init_minix.py"),
        str(disk), str(src), dest], stdout=subprocess.DEVNULL, timeout=60)


def make_disk(disk: Path, runner: Path, tests, files, timeout: int) -> None:
    with disk.open("wb") as fp:
        fp.truncate(DISK_BYTES)
    sh([sys.executable, str(ROOT / "scripts" / "inject_init_minix.py"),
        "--format-large", str(disk)], stdout=subprocess.DEVNULL, timeout=60)
    inject(disk, runner, "sbin/init")
    names = disk_names(files)
    for name, path in files.items():
        inject(disk, path, f"ltp/bin/{names[name]}")
    lines = [f"@timeout {timeout}"]
    for tag, argv in tests:
        lines.append(" ".join([tag, f"/ltp/bin/{names[argv[0]]}", *argv]))
    with tempfile.NamedTemporaryFile("w", suffix=".runlist",
                                     delete=False) as fp:
        fp.write("\n".join(lines) + "\n")
    try:
        inject(disk, Path(fp.name), "ltp/runlist")
    finally:
        os.unlink(fp.name)


def qemu_argv(arch: str, disk: Path, kernel: Path) -> list[str]:
    if arch == "x86_64":
        return ["qemu-system-x86_64", "-cdrom", str(kernel),
                "-drive", f"file={disk},format=raw,if=ide,index=0",
                "-serial", "stdio", "-display", "none", "-no-reboot",
                "-net", "none"]
    return ["qemu-system-aarch64", "-M", "virt,gic-version=2",
            "-cpu", "cortex-a57", "-global", "virtio-mmio.force-legacy=false",
            "-kernel", str(kernel), "-append", "root=/dev/vda",
            "-nographic", "-serial", "mon:stdio",
            "-drive", f"file={disk},format=raw,if=none,id=ltp",
            "-device", "virtio-blk-device,drive=ltp", "-display", "none",
            "-no-reboot"]


def default_kernel(arch: str) -> Path:
    if arch == "x86_64":
        return ROOT / "kernel-x64-userspace.iso"
    img = ROOT / "kernel-arm64-product.img"
    return img if img.is_file() else ROOT / "kernel-arm64-product.bin"


def cmd_run(args) -> int:
    arch = args.arch
    build = args.build_dir.resolve()
    src = build / "src"
    out = build / f"build-{ARCHES[arch]}"
    runner = out / "ltp-runner"
    kernel = (args.kernel or default_kernel(arch)).resolve()
    for path, hint in ((runner, "ltp_harness.py build"),
                       (kernel, "build the kernel image first")):
        if not path.is_file():
            raise SystemExit(f"ltp: missing {path} ({hint})")
    chunks = plan_chunks(src, out, args.list)
    numbered = list(enumerate(chunks))
    if args.only_chunk is not None:
        numbered = [numbered[args.only_chunk]]
    args.log_dir.mkdir(parents=True, exist_ok=True)
    worst = 0
    for i, (tests, files) in numbered:
        log = args.log_dir / f"ltp-{arch}-{i}.log"
        log.unlink(missing_ok=True)
        disk = safety.make_temp_disk(prefix="ir0-ltp-")
        try:
            make_disk(disk, runner, tests, files, args.test_timeout)
            # smoke_autokill accepts at most an hour; per-test kills are the
            # runner's job, this is only the ceiling for the whole chunk.
            budget = min(3600, args.boot_timeout +
                         len(tests) * args.test_timeout)
            # The payload prints arbitrary text (errno names, "fork failed",
            # OOM messages), so only a kernel panic ends the run early.
            rc = subprocess.run(
                [sys.executable, str(ROOT / "scripts" / "smoke_autokill.py"),
                 "--log", str(log), "--timeout", str(budget),
                 "--stale-sec", str(args.test_timeout + 30),
                 "--mem", args.mem, "--no-default-fail",
                 "--fail", PANIC_RE.pattern, "--success", "LTP_RUN_DONE",
                 "--", *qemu_argv(arch, disk, kernel)],
                cwd=str(ROOT), check=False, timeout=budget + 60).returncode
        finally:
            disk.unlink(missing_ok=True)
        (log.parent / (log.name + ".tags")).write_text(
            "".join(f"{tag}\n" for tag, _ in tests))
        print(f"ltp: {arch} chunk {i}: {len(tests)} tests rc={rc} log={log}")
        worst = worst or rc
    return worst


# --- results ----------------------------------------------------------------

def log_arch(log: Path) -> str:
    match = re.match(r"ltp-(x86_64|arm64)-\d+\.log$", log.name)
    if not match:
        raise SystemExit(f"ltp: cannot tell the arch of {log} "
                         "(expected ltp-<arch>-<n>.log)")
    return match.group(1)


def parse_log(log: Path, excerpts: Path | None):
    """[(test, result)] in run order, plus tests the run never reached."""
    tags_file = log.parent / (log.name + ".tags")
    planned = tags_file.read_text().split() if tags_file.is_file() else []
    rows: dict[str, str] = {}
    current, buf, panicked, done = None, [], False, False
    for line in safety.iter_log_lines(log):
        if (m := BEGIN_RE.search(line)):
            current, buf = m.group(1), []
            continue
        if (m := RESULT_RE.search(line)):
            rows[m.group(1)] = m.group(2)
            if excerpts and m.group(2) != "PASS":
                write_excerpt(excerpts, log, m.group(1), buf)
            current = None
            continue
        if DONE_RE.search(line):
            done = True
        if PANIC_RE.search(line):
            panicked = True
        if current is not None and len(buf) < 400:
            buf.append(line)
    if current is not None:
        rows[current] = "PANIC" if panicked else "HANG"
        if excerpts:
            write_excerpt(excerpts, log, current, buf)
    order = planned or list(rows)
    result = [(t, rows[t]) for t in order if t in rows]
    unreached = [t for t in planned if t not in rows]
    if not done and current is None and unreached:
        # Died between tests (panic or stall outside a test).
        first = unreached.pop(0)
        result.append((first, "PANIC" if panicked else "HANG"))
    return result, unreached


def write_excerpt(root: Path, log: Path, test: str, lines: list[str]) -> None:
    path = root / log_arch(log) / f"{test}.log"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def read_results(path: Path) -> list[list[str]]:
    rows = []
    if path.is_file():
        for raw in path.read_text(encoding="utf-8").splitlines():
            if raw.strip() and not raw.lstrip().startswith("#"):
                fields = raw.split("\t")
                rows.append((fields + ["", "", "", ""])[:4])
    return rows


def cmd_results(args) -> int:
    new: dict[str, list[tuple[str, str]]] = {}
    status = 0
    for log in args.logs:
        arch = log_arch(log)
        rows, unreached = parse_log(log, args.excerpts)
        new.setdefault(arch, []).extend(rows)
        fatal = [f"{t} {r}" for t, r in rows if r in FATAL_RESULTS]
        print(f"ltp: {log.name}: {len(rows)} results"
              + (f", fatal: {', '.join(fatal)}" if fatal else "")
              + (f", {len(unreached)} tests never ran" if unreached else ""))
        if fatal or unreached:
            status = 1
    old = [] if args.fresh else read_results(args.output)
    triage = {(a, t, r): tr for a, t, r, tr in old}
    keep = [row for row in old if row[0] not in new]
    lines = ["\t".join(row).rstrip("\t") for row in keep]
    for arch in sorted(new):
        for test, result in new[arch]:
            tr = triage.get((arch, test, result), "")
            lines.append("\t".join(filter(None, (arch, test, result, tr))))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(TSV_HEADER + "".join(f"{l}\n" for l in lines),
                           encoding="utf-8")
    print(f"ltp: wrote {len(lines)} rows to {args.output}")
    return status


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    for name in ("build", "run"):
        p = sub.add_parser(name)
        p.add_argument("--arch", choices=sorted(ARCHES), required=True)
        p.add_argument("--build-dir", type=Path, default=default_build_dir())
        p.add_argument("--list", type=Path, default=DEFAULT_LIST)
    build = sub.choices["build"]
    build.add_argument("--jobs", type=int, default=4)
    run = sub.choices["run"]
    run.add_argument("--log-dir", type=Path, required=True)
    run.add_argument("--kernel", type=Path,
                     help="x86_64 ISO or arm64 product image")
    run.add_argument("--test-timeout", type=int, default=120,
                     help="seconds before the runner kills a test")
    run.add_argument("--boot-timeout", type=int, default=120)
    run.add_argument("--mem", default="512M")
    run.add_argument("--only-chunk", type=int)
    res = sub.add_parser("results")
    res.add_argument("logs", type=Path, nargs="+")
    res.add_argument("--output", type=Path, default=RESULTS)
    res.add_argument("--fresh", action="store_true",
                     help="drop the existing file instead of keeping rows of "
                     "other arches and the triage of unchanged results")
    res.add_argument("--excerpts", type=Path,
                     help="write each non-PASS test's output under DIR/<arch>/")
    args = parser.parse_args()
    return {"build": cmd_build, "run": cmd_run, "results": cmd_results}[
        args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
